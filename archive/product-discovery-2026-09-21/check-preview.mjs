import { chromium } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';

await mkdir('preview/qa', { recursive: true });
const BASE = process.env.BASE_URL ?? 'http://127.0.0.1:5173';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('response', response => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`); });
await page.goto(BASE, { waitUntil: 'networkidle' });
await page.screenshot({ path: 'preview/qa/01-hero.png' });
assert.equal(await page.locator('.category').count(), 5);
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
await page.evaluate(() => window.scrollTo(0, innerHeight * 2.35 * .3));
await page.waitForTimeout(1300);
await page.screenshot({ path: 'preview/qa/02-cloud-rise.png' });
await page.evaluate(() => window.scrollTo(0, innerHeight * 2.35 * .55));
await page.waitForTimeout(1300);
assert.equal(await page.locator('.whiteout').evaluate(el => getComputedStyle(el).opacity), '1');
await page.screenshot({ path: 'preview/qa/03-whiteout.png' });
await page.evaluate(() => window.scrollTo(0, innerHeight * 2.35));
await page.waitForTimeout(1400);
await page.screenshot({ path: 'preview/qa/04-collection.png' });
assert.equal(await page.locator('.collection-scene').evaluate(el => el.inert), false);
await page.getByRole('button', { name: 'Silk Toppers', exact: true }).click();
assert.equal(await page.locator('.product-dialog').evaluate(el => el.open), true);
await page.keyboard.press('Escape');
assert.equal(await page.locator('.product-dialog').evaluate(el => el.open), false);
await page.getByRole('link', { name: 'Back to the hero' }).click();
await page.waitForTimeout(3400);
assert.ok(await page.evaluate(() => scrollY < 2));
await page.getByRole('link', { name: 'Shop the collection' }).click();
await page.waitForTimeout(3400);
assert.equal(await page.locator('.collection-scene').evaluate(el => el.inert), false);
await page.setViewportSize({ width: 390, height: 844 });
await page.goto(BASE, { waitUntil: 'networkidle' });
await page.screenshot({ path: 'preview/qa/05-mobile-hero.png' });
await page.getByRole('link', { name: 'Shop the collection' }).click();
await page.waitForTimeout(3400);
await page.screenshot({ path: 'preview/qa/06-mobile-collection.png' });
assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
const bounds = await page.locator('.back-to-hero').boundingBox();
assert.ok(bounds.y + bounds.height <= 844, 'Mobile collection is fully reachable');
await page.emulateMedia({ reducedMotion: 'reduce' });
await page.goto(BASE, { waitUntil: 'networkidle' });
assert.equal(await page.locator('html').evaluate(el => el.classList.contains('motion-enabled')), false);
await page.getByRole('link', { name: 'Shop the collection' }).click();
await page.waitForTimeout(100);
assert.equal(await page.locator('.collection-scene').evaluate(el => el.inert), false);
await page.setViewportSize({ width: 844, height: 390 });
await page.emulateMedia({ reducedMotion: 'no-preference' });
await page.goto(BASE, { waitUntil: 'networkidle' });
assert.equal(await page.locator('html').evaluate(el => el.classList.contains('motion-enabled')), false);
assert.deepEqual(errors, []);
await writeFile('preview/qa/results.json', JSON.stringify({ passed: true, checks: ['desktop hero', 'parallax rise', 'opaque white midpoint', 'collection reveal', 'reverse scroll', 'shop CTA', 'product dialog and Escape', 'mobile overflow and collection fit', 'reduced motion', 'short viewport fallback'], errors }, null, 2));
await browser.close();
console.log('All preview checks passed. Screenshots saved in preview/qa.');
