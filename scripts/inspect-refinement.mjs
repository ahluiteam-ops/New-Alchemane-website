import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' });
await page.keyboard.press('Tab');
assert.equal(await page.locator('.skip-link').evaluate(el => el === document.activeElement && el.getBoundingClientRect().top >= 0), true);
await page.keyboard.press('Tab');
await page.locator('#consultation').scrollIntoViewIfNeeded();
await page.waitForTimeout(800);
assert.equal(await page.locator('.skip-link').evaluate(el => getComputedStyle(el).clipPath), 'inset(50%)');
await page.locator('#consultation').screenshot({ path: 'preview/homepage-qa/mobile-consultation.png' });
await page.locator('#range').scrollIntoViewIfNeeded();
await page.waitForTimeout(800);
await page.locator('#range').screenshot({ path: 'preview/homepage-qa/mobile-range.png' });
await page.setViewportSize({ width: 1440, height: 1000 });
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' });
await page.locator('.films-pair').scrollIntoViewIfNeeded();
await page.locator('.films-pair').screenshot({ path: 'preview/homepage-qa/desktop-reels-pair.png' });
await browser.close();
